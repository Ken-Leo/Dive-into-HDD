"""Figure style and export helpers for the book.

All book figures must be generated by scripts (no manual screenshots) and
saved through :func:`save_figure` so that fonts, size and DPI are consistent.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # headless-safe; experiments run in CI/terminals

import matplotlib.pyplot as plt

from . import config


def apply_style() -> None:
    """Apply the book's figure style (CJK fonts, vector-friendly settings)."""
    plt.rcParams.update(
        {
            "font.family": "sans-serif",
            "font.sans-serif": config.CJK_FONTS,
            "axes.unicode_minus": False,
            "font.size": 10,
            "axes.labelsize": 10,
            "axes.titlesize": 11,
            "legend.fontsize": 9,
            "xtick.labelsize": 9,
            "ytick.labelsize": 9,
            "figure.figsize": (6.4, 4.2),
            "figure.dpi": 120,
            "savefig.dpi": 300,
            "savefig.bbox": "tight",
            "savefig.transparent": False,
            "figure.facecolor": "white",
            "savefig.facecolor": "white",
            "axes.facecolor": "white",
            "axes.grid": True,
            "grid.alpha": 0.3,
            "lines.linewidth": 1.4,
        }
    )


def save_figure(fig, out_path: str | Path, *, pdf: bool = True) -> Path:
    """Save ``fig`` as PNG (and PDF by default) and return the PNG path."""
    out = Path(out_path)
    config.ensure_dir(out.parent)
    fig.savefig(out)
    if pdf:
        fig.savefig(out.with_suffix(".pdf"))
    plt.close(fig)
    return out


def plain_log_axis(ax, axis: str = "both") -> None:
    """把对数轴的刻度标签改为普通十进制数字。

    matplotlib 对数轴默认用 ``$\\mathdefault{10^{-4}}$`` 形式的刻度标签，
    该标签走 ``\\mathdefault`` 字体（即 font.family 指定的中文字体）；而
    Hiragino Sans GB 等中文字体缺少 U+2212（数学减号），会在刻度上留下方框。
    本函数用纯文本 formatter 规避该问题，保证图件无缺字。
    """
    from matplotlib.ticker import FuncFormatter, NullFormatter

    def _fmt(v, _pos):
        if v >= 1.0:
            return f"{v:g}"
        s = f"{v:.6f}".rstrip("0").rstrip(".")
        return s if s else "0"

    fmt = FuncFormatter(_fmt)
    if axis in ("x", "both"):
        ax.xaxis.set_major_formatter(fmt)
        ax.xaxis.set_minor_formatter(NullFormatter())
    if axis in ("y", "both"):
        ax.yaxis.set_major_formatter(fmt)
        ax.yaxis.set_minor_formatter(NullFormatter())
